_LINHAS_TOTAL = (
    "das", "maximo", "oliveira", "gabriel", "aluguel", "variaveis",
    "internet", "emprestimo_nu", "gasolina", "investimento",
)


def contas_do_mes(valores, salario, pagos, cards, acrescimos=None):
    """Total a pagar sai do salário.

    Entram Das, Max, Oliveira, Gabriel, Pessoa, Variáveis, Internet,
    as faturas, Empréstimo Nu, Gasolina e Investimento. Os dois
    empréstimos não entram de novo: já estão em Oliveira. Assinatura
    ligada a um cartão soma na fatura, junto com o valor digitado nela
    e com os acréscimos lançados nessa fatura.
    """
    marcados = set(pagos or [])
    acrescimos = acrescimos or {}
    ativos = [card for card in cards if card.get("ativo", True)]
    por_id = {card["id"]: card for card in ativos}
    extras = {}
    for card in ativos:
        if card.get("categoria") != "assinaturas" or not card.get("cartao"):
            continue
        codigo = card["cartao"]
        extras[codigo] = extras.get(codigo, Decimal("0.00")) + dinheiro(valores.get(card["id"], 0))
    total = Decimal("0.00")
    pago = Decimal("0.00")

    def somar(identificador, valor):
        nonlocal total, pago
        total += valor
        if identificador in marcados:
            pago += valor

    for item in _LINHAS_TOTAL:
        card = por_id.get(item)
        if card and card.get("categoria") == "assinaturas" and card.get("cartao"):
            continue
        somar(item, dinheiro(valores.get(item, 0)))
    for card in ativos:
        if card.get("categoria") != "cartoes":
            continue
        valor = (
            dinheiro(valores.get(card["id"], 0))
            + extras.get(card["id"], Decimal("0.00"))
            + dinheiro(acrescimos.get(card["id"], 0))
        )
        somar(card["id"], valor)
    for card in ativos:
        if card.get("categoria") not in ("pessoas", "variaveis", "custo_fixo", "taxas"):
            continue
        if card["id"] in _LINHAS_TOTAL:
            continue
        somar(card["id"], dinheiro(valores.get(card["id"], 0)))
    total = dinheiro(total)
    pago = dinheiro(pago)
    salario = dinheiro(salario)
    return total, pago, dinheiro(total - pago), dinheiro(salario - total)


def _calculados(valores, salario, entra, pagos, formulas=None, acrescimos=None):
    return contas_do_mes(valores, salario, pagos, _CARDS, acrescimos)


def _fora_aberto(valores, entra, pagos):
    dentro = set(entra)
    marcados = set(pagos)
    return dinheiro(sum(
        (
            dinheiro(valores.get(card["id"], 0))
            for card in _cards_ativos()
            if card["id"] not in dentro and card["id"] not in marcados and dinheiro(valores.get(card["id"], 0)) > 0
        ),
        Decimal("0.00"),
    ))


def _select_contab():
    despesas = ", ".join(campo["coluna"] for campo in CAMPOS)
    return f"ID, TO_CHAR(MES, 'YYYY-MM'), SALARIO, ITENS_PAGOS, ITENS_NO_TOTAL, DETALHES, {despesas}, FORMULAS"


def _ler_linha(row):
    valores = {campo["id"]: dinheiro(row[6 + indice]) for indice, campo in enumerate(CAMPOS)}
    entra = _ids(row[4], PADRAO_ENTRA) or list(PADRAO_ENTRA)
    pagos = _ids(row[3])
    detalhes = {}
    if row[5]:
        try:
            carregado = json.loads(row[5])
            if isinstance(carregado, dict):
                detalhes = {chave: str(valor) for chave, valor in carregado.items() if chave in _IDS}
        except json.JSONDecodeError:
            detalhes = {}
    formulas = {}
    bruto_formula = row[6 + len(CAMPOS)] if len(row) > 6 + len(CAMPOS) else None
    if bruto_formula:
        try:
            carregado = json.loads(bruto_formula)
            if isinstance(carregado, dict):
                formulas = carregado
        except json.JSONDecodeError:
            formulas = {}
    return {
        "id": int(row[0]),
        "mes": row[1],
        "salario": dinheiro(row[2]),
        "valores": valores,
        "entra": entra,
        "pagos": pagos,
        "detalhes": detalhes,
        "formulas": formulas,
    }


def _aplicar_extras(linhas, extras):
    for linha in linhas:
        do_mes = extras.get(linha["mes"], {})
        for card in _CARDS:
            if card["sistema"]:
                continue
            linha["valores"][card["id"]] = do_mes.get(card["id"], Decimal("0.00"))


def _ler_mes(cur, mes):
    cur.execute(
        f"""
        SELECT {_select_contab()}
        FROM CONTABILIDADE_GERAL
        WHERE TRUNC(MES, 'MM') = TRUNC(:mes, 'MM')
        """,
        mes=_mes_data(mes),
    )
    row = cur.fetchone()
    if not row:
        return None
    linha = _ler_linha(row)
    _aplicar_extras([linha], catalogo.extras_por_mes(cur))
    return linha


def _acrescimos_mes(cur, mes):
    cur.execute(
        """
        SELECT APELIDO, NVL(SUM(VALOR), 0)
        FROM OBSERVACOES
        WHERE TIPO = 'fatura' AND TRUNC(MES, 'MM') = TRUNC(:mes, 'MM')
        GROUP BY APELIDO
        """,
        mes=_mes_data(mes),
    )
    return {str(apelido): dinheiro(valor) for apelido, valor in cur if apelido}


def _gravar_calculados(cur, mes, salario, valores, entra, pagos, formulas=None):
    total, pago, faltante, sobra = _calculados(
        valores, salario, entra, pagos, formulas, _acrescimos_mes(cur, mes)
    )
    cur.execute(
        """
        UPDATE CONTABILIDADE_GERAL
        SET VALOR_PAGO = :pago,
            TOTAL_A_PAGAR = :total,
            VALOR_FALTANTE = :faltante,
            SOBRA = :sobra
        WHERE TRUNC(MES, 'MM') = TRUNC(:mes, 'MM')
        """,
        pago=pago,
        total=total,
        faltante=faltante,
        sobra=sobra,
        mes=_mes_data(mes),
    )


def _tem_emprestimo(cur, mes):
    cur.execute(
        """
        SELECT COUNT(*) FROM EMPRESTIMOS
        WHERE TRUNC(MES, 'MM') = TRUNC(:mes, 'MM')
        """,
        mes=_mes_data(mes),
    )
    return cur.fetchone()[0] > 0


def _soma_parcelas(cur, mes):
    cur.execute(
        """
        SELECT NVL(SUM(NVL(PAGAMENTO, 0) + NVL(JUROS, 0)), 0)
        FROM EMPRESTIMOS
        WHERE TRUNC(MES, 'MM') = TRUNC(:mes, 'MM')
        """,
        mes=_mes_data(mes),
    )
    return dinheiro(cur.fetchone()[0])


def _sync_oliveira(cur, meses):
    for mes in sorted(set(meses)):
        if not _tem_emprestimo(cur, mes):
            continue
        cur.execute(
            """
            UPDATE CONTABILIDADE_GERAL
            SET OLIVEIRA = :valor
            WHERE TRUNC(MES, 'MM') = TRUNC(:mes, 'MM')
            """,
            valor=_soma_parcelas(cur, mes),
            mes=_mes_data(mes),
        )
        linha = _ler_mes(cur, mes)
        if linha:
            _gravar_calculados(
                cur, mes, linha["salario"], linha["valores"], linha["entra"], linha["pagos"], linha.get("formulas")
            )


def _upsert_mes(cur, mes, salario, valores, entra, pagos, detalhes, substituir_meta, formulas=None):
    if formulas is None:
        cur.execute(
            """
            SELECT FORMULAS FROM CONTABILIDADE_GERAL
            WHERE TRUNC(MES, 'MM') = TRUNC(:mes, 'MM')
            """,
            mes=_mes_data(mes),
        )
        achado = cur.fetchone()
        if achado and achado[0]:
            try:
                formulas = json.loads(achado[0])
            except json.JSONDecodeError:
                formulas = {}
        else:
            formulas = {}
    total, pago, faltante, sobra = _calculados(
        valores, salario, entra, pagos, formulas, _acrescimos_mes(cur, mes)
    )
    binds = {
        "mes": _mes_data(mes),
        "salario": salario,
        "valor_pago": pago,
        "total": total,
        "faltante": faltante,
        "sobra": sobra,
        "itens_pagos": _csv(pagos),
        "itens_no_total": _csv(entra),
        "detalhes": json.dumps(detalhes, ensure_ascii=False) if detalhes else None,
        "formulas": json.dumps(formulas, ensure_ascii=False) if formulas else None,
    }
    for campo in CAMPOS:
        binds[campo["id"]] = valores[campo["id"]]
    despesas_set = ", ".join(f"{campo['coluna']} = :{campo['id']}" for campo in CAMPOS)
    meta = ""
    if substituir_meta:
        meta = ", ITENS_NO_TOTAL = :itens_no_total, DETALHES = :detalhes"
    cur.execute(
        f"""
        MERGE INTO CONTABILIDADE_GERAL t
        USING (SELECT TRUNC(:mes, 'MM') AS mes FROM dual) s
        ON (TRUNC(t.MES, 'MM') = s.mes)
        WHEN MATCHED THEN UPDATE SET
            SALARIO = :salario,
            VALOR_PAGO = :valor_pago,
            TOTAL_A_PAGAR = :total,
            VALOR_FALTANTE = :faltante,
            SOBRA = :sobra,
            ITENS_PAGOS = :itens_pagos,
            FORMULAS = :formulas
            {meta},
            {despesas_set}
        WHEN NOT MATCHED THEN INSERT (
            MES, SALARIO, VALOR_PAGO, TOTAL_A_PAGAR, VALOR_FALTANTE, SOBRA,
            ITENS_PAGOS, ITENS_NO_TOTAL, DETALHES, FORMULAS, {", ".join(campo["coluna"] for campo in CAMPOS)}
        ) VALUES (
            :mes, :salario, :valor_pago, :total, :faltante, :sobra,
            :itens_pagos, :itens_no_total, :detalhes, :formulas, {", ".join(":" + campo["id"] for campo in CAMPOS)}
        )
        """,
        **binds,
    )


def aplicar_planilha(conn=None):
    proprio = conn is None
    if proprio:
        conn = pool.acquire()
    livro = ler_planilha()
    try:
        cur = conn.cursor()
        for mes, info in livro["meses"].items():
            _upsert_mes(
                cur,
                mes,
                info["salario"],
                info["valores"],
                info["entra"],
                info["pagos"],
                info["detalhes"],
                substituir_meta=True,
                formulas=info["formulas"],
            )
        cur.execute("DELETE FROM EMPRESTIMOS")
        cur.executemany(
            """
            INSERT INTO EMPRESTIMOS (
                MES, EMPRESTIMO, SALDO_INICIO, JUROS, PAGAMENTO, PAGAMENTO_COM_JUROS, PAGAMENTO_PREVISTO, PAGO
            ) VALUES (
                :mes, :emprestimo, :saldo_inicio, :juros, :pagamento, :pagamento_com_juros, :previsto, :pago
            )
            """,
            [
                {
                    "mes": _mes_data(item["mes"]),
                    "emprestimo": item["emprestimo"],
                    "saldo_inicio": item["saldo_inicio"],
                    "juros": item["juros"],
                    "pagamento": item["pagamento"],
                    "pagamento_com_juros": item["pagamento_com_juros"],
                    "previsto": item["pagamento_previsto"],
                    "pago": 1 if item["pago"] else 0,
                }
                for item in livro["emprestimos"]
            ],
        )
        cur.execute("DELETE FROM OBSERVACOES")
        if livro["observacoes"]:
            cur.executemany(
                """
                INSERT INTO OBSERVACOES (MES, VALOR, TEXTO, TIPO)
                VALUES (:mes, :valor, :texto, :tipo)
                """,
                [
                    {
                        "mes": _mes_data(nota["mes"]),
                        "valor": nota["valor"],
                        "texto": nota["texto"],
                        "tipo": nota["tipo"],
                    }
                    for nota in livro["observacoes"]
                ],
            )
        _incluir_investimento(cur)
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        if proprio:
            conn.close()
    return {
        "arquivo": livro["arquivo"],
        "meses": len(livro["meses"]),
        "emprestimos": len(livro["emprestimos"]),
        "observacoes": len(livro["observacoes"]),
    }


def sem_valores(conn):
    cur = conn.cursor()
    soma = " + ".join(f"NVL({campo['coluna']}, 0)" for campo in CAMPOS)
    cur.execute(f"SELECT NVL(SUM({soma}), 0) FROM CONTABILIDADE_GERAL")
    return dinheiro(cur.fetchone()[0]) == 0


def preparar(importar=False):
    iniciar_pool()
    with pool.acquire() as conn:
        ensure_schema(conn)
        if importar or sem_valores(conn):
            return aplicar_planilha(conn)
    return None


def _publico_contab(linha, meses_emprestimo, acrescimos=None):
    valores = {chave: float(valor) for chave, valor in linha["valores"].items()}
    total, pago, faltante, sobra = _calculados(
        linha["valores"], linha["salario"], linha["entra"], linha["pagos"], linha.get("formulas"), acrescimos
    )
    dados = {
        "id": linha["id"],
        "mes": linha["mes"],
        "salario": float(linha["salario"]),
        "valor_pago": float(pago),
        "total_a_pagar": float(total),
        "valor_faltante": float(faltante),
        "sobra": float(sobra),
        "fora_aberto": float(_fora_aberto(linha["valores"], linha["entra"], linha["pagos"])),
        "entra": linha["entra"],
        "itens_pagos": linha["pagos"],
        "detalhes": linha["detalhes"],
        "formulas": linha.get("formulas") or {},
        "oliveira_calculado": linha["mes"] in meses_emprestimo,
    }
    dados.update(valores)
    return dados


def _alertas(observacoes):
    por_mes = {}
    for nota in observacoes:
        por_mes.setdefault(nota["mes"], []).append(nota)
    alertas = []
    for mes, notas in por_mes.items():
        soma = sum(nota["valor"] for nota in notas if nota["tipo"] == "nubank")
        totais = [nota["valor"] for nota in notas if nota["tipo"] == "nubank_total"]
        if totais and abs(soma - totais[0]) >= 0.009:
            alertas.append({"mes": mes, "soma": round(soma, 2), "esperado": round(totais[0], 2)})
    return alertas


def buscar_tudo():
    with pool.acquire() as conn:
        cur = conn.cursor()
        _usar_cards(cur)
        cur.execute(f"SELECT {_select_contab()} FROM CONTABILIDADE_GERAL ORDER BY MES, ID")
        linhas = [_ler_linha(row) for row in cur]
        _aplicar_extras(linhas, catalogo.extras_por_mes(cur))
        cur.execute(
            """
            SELECT ID, TO_CHAR(MES, 'YYYY-MM'), EMPRESTIMO, SALDO_INICIO, JUROS, PAGAMENTO,
                   PAGAMENTO_COM_JUROS, SALDO_FIM, TOTAL_PAGO_MES, PAGO, PAGAMENTO_PREVISTO
            FROM EMPRESTIMOS
            ORDER BY MES, EMPRESTIMO, ID
            """
        )
        emprestimos = []
        meses_emprestimo = set()
        for row in cur:
            mes = row[1]
            numero = int(row[2])
            meses_emprestimo.add(mes)
            emprestimos.append({
                "id": int(row[0]),
                "mes": mes,
                "emprestimo": numero,
                "saldo_inicio": float(dinheiro(row[3])),
                "juros": float(dinheiro(row[4])),
                "pagamento": float(dinheiro(row[5])),
                "pagamento_com_juros": float(dinheiro(row[6])),
                "saldo_fim": float(dinheiro(row[7])),
                "total_pago_mes": float(dinheiro(row[8])),
                "pago": int(row[9] or 0) == 1,
                "pagamento_previsto": float(dinheiro(row[10] if row[10] is not None else row[5])),
                "categoria": f"Empréstimo {numero}",
            })
        cur.execute(
            """
            SELECT ID, TO_CHAR(MES, 'YYYY-MM'), VALOR, TEXTO, TIPO, APELIDO
            FROM OBSERVACOES
            ORDER BY MES, ID
            """
        )
        observacoes = [
            {
                "id": int(row[0]),
                "mes": row[1],
                "valor": float(dinheiro(row[2])),
                "texto": row[3],
                "tipo": row[4],
                "apelido": row[5] or "",
            }
            for row in cur
        ]
        cur.execute(
            """
            SELECT ID, TO_CHAR(MES, 'YYYY-MM'), EMPRESTIMO, VALOR, SALDO, TEXTO
            FROM HISTORICO
            ORDER BY ID DESC
            """
        )
        historico = [
            {
                "id": int(row[0]),
                "mes": row[1],
                "emprestimo": int(row[2]),
                "valor": float(dinheiro(row[3])),
                "saldo": float(dinheiro(row[4])),
                "texto": row[5],
            }
            for row in cur
        ]
    acrescimos = {}
    for nota in observacoes:
        if nota["tipo"] != "fatura" or not nota["apelido"]:
            continue
        do_mes = acrescimos.setdefault(nota["mes"], {})
        do_mes[nota["apelido"]] = do_mes.get(nota["apelido"], 0) + nota["valor"]
    return {
        "contabilidade": [
            _publico_contab(linha, meses_emprestimo, acrescimos.get(linha["mes"]))
            for linha in linhas
        ],
        "emprestimos": emprestimos,
        "observacoes": observacoes,
        "historico": historico,
        "alertas": _alertas(observacoes),
        "campos": [_campo_publico(card) for card in _CARDS if card["ativo"]],
        "ocultos": [_campo_publico(card) for card in _CARDS if not card["ativo"]],
        "categorias": [
            {"id": identificador, "label": rotulo, "icone": icone}
            for identificador, rotulo, icone in CATEGORIAS
        ],
    }


def salvar_contabilidade(payload):
    mes = _exigir_mes(payload.get("mes"))
    with pool.acquire() as conn:
        cur = conn.cursor()
        _usar_cards(cur)
        atual = _ler_mes(cur, mes)
        base_valores = atual["valores"] if atual else {}
        valores = {}
        for card in _cards_ativos():
            if card["id"] in payload:
                valores[card["id"]] = _exigir_dinheiro(card["label"], payload.get(card["id"]))
            else:
                valores[card["id"]] = dinheiro(base_valores.get(card["id"], 0))
        for campo in CAMPOS:
            if campo["id"] not in valores:
                if campo["id"] in payload:
                    valores[campo["id"]] = _exigir_dinheiro(campo["label"], payload.get(campo["id"]))
                else:
                    valores[campo["id"]] = dinheiro(base_valores.get(campo["id"], 0))
        if "salario" in payload or not atual:
            salario = _exigir_dinheiro("Salário", payload.get("salario"))
        else:
            salario = atual["salario"]
        if "itens_pagos" in payload:
            pagos = _ids(payload.get("itens_pagos"))
        else:
            pagos = atual["pagos"] if atual else []
        if isinstance(payload.get("entra"), list):
            entra = _ids(payload.get("entra"))
        elif atual:
            entra = atual["entra"]
        else:
            entra = [card["id"] for card in _cards_ativos() if card["entra_padrao"]]
        detalhes = atual["detalhes"] if atual else {}
        if _tem_emprestimo(cur, mes) and "oliveira" in _IDS:
            valores["oliveira"] = _soma_parcelas(cur, mes)
        _upsert_mes(cur, mes, salario, valores, entra, pagos, detalhes, substituir_meta=True)
        for card_id, valor in valores.items():
            if card_id not in _COLUNAS:
                catalogo.gravar_extra(cur, _mes_data(mes), card_id, valor)
        conn.commit()
    return buscar_tudo()


