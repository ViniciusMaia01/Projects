def _mes_data(mes):
    return datetime.strptime(mes, "%Y-%m")


def _exigir_mes(mes):
    texto = str(mes or "")
    if not re.fullmatch(r"\d{4}-\d{2}", texto):
        raise ErroValidacao("Informe o mês.")
    if not 1 <= int(texto[5:]) <= 12:
        raise ErroValidacao("Mês inválido.")
    return texto


def _exigir_dinheiro(nome, valor):
    try:
        dec = dinheiro(valor)
    except Exception as exc:
        raise ErroValidacao(f"{nome} precisa ser um valor em reais.") from exc
    if not dec.is_finite():
        raise ErroValidacao(f"{nome} precisa ser um valor em reais.")
    if dec < 0:
        raise ErroValidacao(f"{nome} não pode ser negativo.")
    if dec > Decimal("1000000"):
        raise ErroValidacao(f"{nome} passou de R$ 1.000.000,00.")
    return dec


def _ids(valor, atual=None):
    if valor is None:
        bruto = atual or []
    elif isinstance(valor, str):
        bruto = valor.split(",")
    else:
        bruto = valor
    return [item for item in bruto if item in _IDS]


def _csv(itens):
    escolhidos = set(itens)
    ordem = _CARDS or [{"id": campo["id"]} for campo in CAMPOS]
    return ",".join(card["id"] for card in ordem if card["id"] in escolhidos)


def _legivel(mes):
    ano, numero = mes.split("-")
    return f"{_MESES[int(numero) - 1]} de {ano}"


