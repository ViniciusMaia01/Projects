def _cursor_colunas(cur):
    cur.execute(
        """
        SELECT column_name, virtual_column
        FROM user_tab_cols
        WHERE table_name = 'CONTABILIDADE_GERAL' AND hidden_column = 'NO'
        """
    )
    return {nome: virtual for nome, virtual in cur}


def _garantir_numero(cur, colunas, nome):
    if colunas.get(nome) == "YES":
        cur.execute(f"ALTER TABLE CONTABILIDADE_GERAL DROP COLUMN {nome}")
        colunas.pop(nome, None)
    if nome not in colunas:
        cur.execute(f"ALTER TABLE CONTABILIDADE_GERAL ADD ({nome} NUMBER(12,2) DEFAULT 0 NOT NULL)")
        colunas[nome] = "NO"


