def _flag(valor):
    return 1 if valor in (1, True, "1", "true", "True") else 0


def _upsert_emprestimo(cur, item, saldo, pagamento, juros):
    dados = {
        "mes": _mes_data(item["mes"]),
        "emprestimo": int(item["emprestimo"]),
        "saldo_inicio": saldo,
        "juros": juros,
        "pagamento": pagamento,
        "pagamento_com_juros": dinheiro(pagamento + juros),
        "pago": _flag(item.get("pago")),
    }
    row_id = item.get("id")
    if row_id:
        cur.execute(
            """
            UPDATE EMPRESTIMOS
            SET MES = :mes, EMPRESTIMO = :emprestimo, SALDO_INICIO = :saldo_inicio,
                JUROS = :juros, PAGAMENTO = :pagamento, PAGAMENTO_COM_JUROS = :pagamento_com_juros,
                PAGO = :pago
            WHERE ID = :id
            """,
            **dados,
            id=int(row_id),
        )
        return
    cur.execute(
        """
        INSERT INTO EMPRESTIMOS (
            MES, EMPRESTIMO, SALDO_INICIO, JUROS, PAGAMENTO, PAGAMENTO_COM_JUROS, PAGO
        ) VALUES (
            :mes, :emprestimo, :saldo_inicio, :juros, :pagamento, :pagamento_com_juros, :pago
        )
        """,
        **dados,
    )


def _cascatear(cur, numero, desde, ancorar):
    cur.execute(
        """
        SELECT ID, TO_CHAR(MES, 'YYYY-MM'), SALDO_INICIO, PAGAMENTO,
               NVL(PAGAMENTO_PREVISTO, PAGAMENTO)
        FROM EMPRESTIMOS
        WHERE EMPRESTIMO = :numero
        ORDER BY MES
        """,
        numero=numero,
    )
    linhas = cur.fetchall()
    avisos = []
    meses = []
    anterior = None
    for row_id, mes, saldo, pagamento, previsto in linhas:
        saldo = dinheiro(saldo)
        pagamento = dinheiro(pagamento)
        previsto = dinheiro(previsto)
        if mes < desde:
            anterior = dinheiro(saldo - pagamento)
            continue
        if mes == desde and ancorar:
            juros = dinheiro(saldo * _TAXA)
            cur.execute(
                """
                UPDATE EMPRESTIMOS
                SET JUROS = :juros, PAGAMENTO_COM_JUROS = :pagj
                WHERE ID = :id
                """,
                juros=juros,
                pagj=dinheiro(pagamento + juros),
                id=row_id,
            )
            anterior = dinheiro(saldo - pagamento)
            meses.append(mes)
            continue
        saldo = anterior if anterior and anterior > 0 else Decimal("0.00")
        parcela = previsto if previsto > 0 else pagamento
        if parcela > saldo:
            avisos.append(
                f"Empréstimo {numero} em {_legivel(mes)}: a parcela de {parcela} foi limitada ao saldo de {saldo}."
            )
            parcela = saldo
        juros = dinheiro(saldo * _TAXA)
        cur.execute(
            """
            UPDATE EMPRESTIMOS
            SET SALDO_INICIO = :saldo, JUROS = :juros, PAGAMENTO = :pagamento,
                PAGAMENTO_COM_JUROS = :pagj
            WHERE ID = :id
            """,
            saldo=saldo,
            juros=juros,
            pagamento=parcela,
            pagj=dinheiro(parcela + juros),
            id=row_id,
        )
        anterior = dinheiro(saldo - parcela)
        meses.append(mes)
    return avisos, meses


def salvar_emprestimos_lote(payload):
    itens = payload.get("emprestimos") or []
    if not isinstance(itens, list):
        raise ErroValidacao("Lista de empréstimos inválida.")
    avisos = []
    with pool.acquire() as conn:
        cur = conn.cursor()
        editados = {}
        meses = set()
        try:
            for item in itens:
                mes = _exigir_mes(item.get("mes"))
                numero = int(item.get("emprestimo") or 0)
                if numero not in (1, 2):
                    raise ErroValidacao("O empréstimo precisa ser 1 ou 2.")
                meses.add(mes)
                if not item.get("alterar_valores"):
                    if item.get("id"):
                        cur.execute(
                            "UPDATE EMPRESTIMOS SET PAGO = :pago WHERE ID = :id",
                            pago=_flag(item.get("pago")),
                            id=int(item["id"]),
                        )
                    continue
                saldo = _exigir_dinheiro("Saldo", item.get("saldo_inicio"))
                pagamento = _exigir_dinheiro("Pagamento", item.get("pagamento"))
                if pagamento > saldo:
                    raise ErroValidacao(
                        f"No empréstimo {numero} de {_legivel(mes)}, o pagamento não pode passar do saldo."
                    )
                _upsert_emprestimo(cur, {**item, "mes": mes, "emprestimo": numero}, saldo, pagamento, dinheiro(saldo * _TAXA))
                editados[numero] = min(editados.get(numero, mes), mes)
            for numero, mes in editados.items():
                novos, afetados = _cascatear(cur, numero, mes, ancorar=True)
                avisos.extend(novos)
                meses.update(afetados)
            _sync_oliveira(cur, meses)
            conn.commit()
        except Exception:
            conn.rollback()
            raise
    dados = buscar_tudo()
    if avisos:
        dados["avisos"] = avisos
    return dados


def salvar_emprestimo(payload):
    payload = dict(payload)
    payload["alterar_valores"] = True
    return salvar_emprestimos_lote({"emprestimos": [payload]})


def quitar_emprestimo(payload):
    mes = _exigir_mes(payload.get("mes"))
    numero = int(payload.get("emprestimo") or 0)
    if numero not in (1, 2):
        raise ErroValidacao("O empréstimo precisa ser 1 ou 2.")
    avisos = []
    with pool.acquire() as conn:
        cur = conn.cursor()
        try:
            cur.execute(
                """
                SELECT ID, SALDO_INICIO
                FROM EMPRESTIMOS
                WHERE EMPRESTIMO = :numero AND TRUNC(MES, 'MM') = TRUNC(:mes, 'MM')
                """,
                numero=numero,
                mes=_mes_data(mes),
            )
            achado = cur.fetchone()
            if not achado:
                raise ErroValidacao("Não há parcela deste empréstimo neste mês.")
            row_id, saldo = int(achado[0]), dinheiro(achado[1])
            if saldo <= 0:
                raise ErroValidacao("Esse empréstimo já está quitado.")
            juros = dinheiro(saldo * _TAXA)
            cur.execute(
                """
                UPDATE EMPRESTIMOS
                SET PAGAMENTO = :pag, JUROS = :juros, PAGAMENTO_COM_JUROS = :pagj, PAGO = 1
                WHERE ID = :id
                """,
                pag=saldo,
                juros=juros,
                pagj=dinheiro(saldo + juros),
                id=row_id,
            )
            novos, afetados = _cascatear(cur, numero, mes, ancorar=True)
            avisos.extend(novos)
            _sync_oliveira(cur, [mes, *afetados])
            cur.execute(
                """
                INSERT INTO HISTORICO (MES, EMPRESTIMO, VALOR, SALDO, TEXTO)
                VALUES (:mes, :emp, :valor, 0, :texto)
                """,
                mes=_mes_data(mes),
                emp=numero,
                valor=dinheiro(saldo + juros),
                texto=f"Empréstimo {numero} quitado em {_legivel(mes)}. Pago {dinheiro(saldo + juros)} (saldo {saldo} e juros {juros}) e o saldo seguinte ficou zerado.",
            )
            conn.commit()
        except Exception:
            conn.rollback()
            raise
    dados = buscar_tudo()
    if avisos:
        dados["avisos"] = avisos
    return dados


def excluir_emprestimo(row_id):
    with pool.acquire() as conn:
        cur = conn.cursor()
        cur.execute(
            "SELECT EMPRESTIMO, TO_CHAR(MES, 'YYYY-MM') FROM EMPRESTIMOS WHERE ID = :id",
            id=int(row_id),
        )
        achado = cur.fetchone()
        if not achado:
            raise ErroValidacao("Empréstimo não encontrado.")
        numero, mes = int(achado[0]), achado[1]
        cur.execute("DELETE FROM EMPRESTIMOS WHERE ID = :id", id=int(row_id))
        _, afetados = _cascatear(cur, numero, mes, ancorar=False)
        _sync_oliveira(cur, [mes, *afetados])
        conn.commit()
    return buscar_tudo()


