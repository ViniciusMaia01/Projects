def _preencher_formulas(cur):
    cur.execute("SELECT TO_CHAR(MES, 'YYYY-MM'), FORMULAS FROM CONTABILIDADE_GERAL")
    faltando = [mes for mes, bruto in cur.fetchall() if not bruto or "total" not in str(bruto)]
    if not faltando:
        return
    livro = ler_planilha()
    for mes in faltando:
        info = livro["meses"].get(mes)
        if not info:
            continue
        cur.execute(
            """
            UPDATE CONTABILIDADE_GERAL
            SET FORMULAS = :formulas
            WHERE TRUNC(MES, 'MM') = TRUNC(:mes, 'MM')
            """,
            formulas=json.dumps(info["formulas"], ensure_ascii=False),
            mes=_mes_data(mes),
        )
    _recalcular_meses(cur)


def _incluir_investimento(cur):
    """Investimento sai do salário, então entra no total de todos os meses."""
    cur.execute("UPDATE CARDS SET ENTRA_PADRAO = 1 WHERE ID = 'investimento'")
    cur.execute("SELECT MES, ITENS_NO_TOTAL FROM CONTABILIDADE_GERAL")
    mudou = False
    for mes, atual in cur.fetchall():
        itens = [parte for parte in str(atual or "").split(",") if parte]
        if "investimento" in itens:
            continue
        itens.append("investimento")
        cur.execute(
            "UPDATE CONTABILIDADE_GERAL SET ITENS_NO_TOTAL = :itens WHERE MES = :mes",
            itens=",".join(itens),
            mes=mes,
        )
        mudou = True
    if mudou:
        _usar_cards(cur)
        _recalcular_meses(cur)


