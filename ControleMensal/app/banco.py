def repetir_valor(payload):
    mes = _exigir_mes(payload.get("mes"))
    card_id = str(payload.get("campo") or "")
    with pool.acquire() as conn:
        _usar_cards(conn.cursor())
    card = next((item for item in _CARDS if item["id"] == card_id), None)
    if not card:
        raise ErroValidacao("Card não encontrado.")
    valor = _exigir_dinheiro(card["label"], payload.get("valor"))

    def acao(cur):
        for destino in catalogo.meses_ate_dezembro(mes):
            if card_id == "oliveira" and _tem_emprestimo(cur, destino):
                continue
            linha = _ler_mes(cur, destino)
            if not linha:
                continue
            linha["valores"][card_id] = valor
            if card_id in _COLUNAS:
                cur.execute(
                    f"""
                    UPDATE CONTABILIDADE_GERAL
                    SET {_COLUNAS[card_id]} = :valor
                    WHERE TRUNC(MES, 'MM') = TRUNC(:mes, 'MM')
                    """,
                    valor=valor,
                    mes=_mes_data(destino),
                )
            else:
                catalogo.gravar_extra(cur, _mes_data(destino), card_id, valor)
            _gravar_calculados(
                cur, destino, linha["salario"], linha["valores"], linha["entra"], linha["pagos"], linha.get("formulas")
            )

    return _com_cards(acao)


